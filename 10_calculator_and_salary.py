#============================================================================

def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def divide(a, b):
    return a / b

#============================================================================

def gross_salary(basic, allowance):
    return basic + allowance


def deductions(gross, deduction):
    return deduction


def net_salary(gross, deduction):
    return gross - deduction
